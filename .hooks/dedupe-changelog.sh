#!/usr/bin/env bash
# Keep the first section of each version in CHANGELOG.md and drop later copies.
#
# `cog bump --pre` renders every pre-release since the last full release again, on
# top of the sections already there (seen on v0.1.0-rc.1 and rc.2), so each bump
# would repeat the earlier release candidates. Runs as a pre-bump hook: cog has
# already written the changelog by then, and the bump commit takes this result.
set -euo pipefail
file="${1:-CHANGELOG.md}"
[[ -f "$file" ]] || exit 0
awk '
  /^## \[/ { version = $2; skip = (version in seen); seen[version] = 1 }
  /^Changelog generated by/ { skip = 0 }
  !skip { print }
' "$file" > "$file.tmp"
mv "$file.tmp" "$file"
